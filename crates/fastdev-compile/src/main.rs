use anyhow::{bail, Context, Result};
use clap::Parser;
use fastdev_common::{Capture, CheckManifest, NodeKind, CAPTURE_SCHEMA_VERSION};
use std::fs;
use std::path::{Path, PathBuf};

/// Compile a capture.json into the per-board artifacts fastdev-prep replays
/// at boot: tmpfiles.conf, a udev-data/ tree, and a check-manifest.json for
/// fastdev-check.
#[derive(Parser)]
struct Args {
    #[arg(long = "in")]
    input: PathBuf,

    #[arg(long)]
    board_id: String,

    #[arg(long)]
    out_dir: PathBuf,

    /// Restrict replayed udev-data and the check-manifest to these
    /// subsystems (repeatable, e.g. --include-subsystem block --include-subsystem net).
    /// Omit to include everything captured - see CheckManifest::from_capture_filtered
    /// for why that's often the wrong default once GPU/optional-module
    /// devices are in the capture.
    #[arg(long = "include-subsystem")]
    include_subsystems: Vec<String>,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let text = fs::read_to_string(&args.input)
        .with_context(|| format!("reading {}", args.input.display()))?;
    let capture: Capture = serde_json::from_str(&text).context("parsing capture json")?;

    if capture.schema_version != CAPTURE_SCHEMA_VERSION {
        bail!(
            "capture schema_version {} does not match fastdev-compile's expected {} - \
             regenerate the capture with a matching fastdev-capture, don't misparse it",
            capture.schema_version,
            CAPTURE_SCHEMA_VERSION
        );
    }

    fs::create_dir_all(&args.out_dir)
        .with_context(|| format!("creating {}", args.out_dir.display()))?;
    let udev_data_dir = args.out_dir.join("udev-data");
    fs::create_dir_all(&udev_data_dir)
        .with_context(|| format!("creating {}", udev_data_dir.display()))?;

    write_tmpfiles_conf(&capture, &args.out_dir.join("tmpfiles.conf"))?;
    let (skipped, included) = write_udev_data(&capture, &udev_data_dir, &args.include_subsystems)?;
    write_check_manifest(&capture, &args.out_dir.join("check-manifest.json"), &args.include_subsystems)?;
    write_fast_rules(&capture, &args.out_dir.join("10-fastdev-precomputed.rules"), &args.include_subsystems)?;

    eprintln!(
        "compiled board '{}': {} /dev nodes, {}/{} devices included ({} subsystem-filtered, {} skipped - no captured db text) -> {}",
        args.board_id,
        capture.nodes.len(),
        included,
        capture.devices.len(),
        capture.devices.len().saturating_sub(included).saturating_sub(skipped),
        skipped,
        args.out_dir.display()
    );
    Ok(())
}

fn write_tmpfiles_conf(capture: &Capture, path: &Path) -> Result<()> {
    let mut out = String::new();
    out.push_str("# Generated by fastdev-compile - do not edit by hand.\n");
    out.push_str("# devtmpfs already creates char/block device nodes with kernel-default\n");
    out.push_str("# perms; the z/d lines below only fix them up where the capture differs.\n");
    out.push_str("# TODO(Milestone 1): drop entries redundant with devtmpfs defaults once\n");
    out.push_str("# that's confirmed against real hardware.\n");
    for node in &capture.nodes {
        match &node.kind {
            NodeKind::Symlink { target } => {
                out.push_str(&format!("L+ {} - - - - {}\n", node.path, target));
            }
            NodeKind::CharDevice { .. } | NodeKind::BlockDevice { .. } => {
                out.push_str(&format!(
                    "z {} {:04o} {} {} - -\n",
                    node.path, node.mode, node.uid, node.gid
                ));
            }
            NodeKind::Directory => {
                out.push_str(&format!(
                    "d {} {:04o} {} {} - -\n",
                    node.path, node.mode, node.uid, node.gid
                ));
            }
        }
    }
    fs::write(path, out).with_context(|| format!("writing {}", path.display()))
}

fn write_udev_data(capture: &Capture, dir: &Path, subsystems: &[String]) -> Result<(usize, usize)> {
    let mut skipped = 0;
    let mut included = 0;
    for device in &capture.devices {
        if !subsystems.is_empty() && !subsystems.contains(&device.subsystem) {
            continue;
        }
        if device.db_text.is_empty() {
            skipped += 1;
            continue;
        }
        let path = dir.join(&device.db_id);
        fs::write(&path, &device.db_text).with_context(|| format!("writing {}", path.display()))?;
        included += 1;
    }
    Ok((skipped, included))
}

fn write_check_manifest(capture: &Capture, path: &Path, subsystems: &[String]) -> Result<()> {
    let manifest = CheckManifest::from_capture_filtered(capture, subsystems);
    let json = serde_json::to_string_pretty(&manifest)?;
    fs::write(path, json).with_context(|| format!("writing {}", path.display()))
}

/// Generates a real udev rule, one stanza per captured block device,
/// matching by exact DEVPATH and pre-setting the ID_FS_* properties real
/// blkid probing would have produced - plus the stock, documented escape
/// hatch (UDEV_DISABLE_PERSISTENT_STORAGE_BLKID_FLAG, see
/// 60-persistent-storage.rules) to skip the actual disk read for that one
/// device.
///
/// Deliberately NOT a global on/off switch: a device whose DEVPATH doesn't
/// match any stanza here (new/different hardware) simply falls through to
/// the real, unmodified stock rule and gets probed normally - per-device
/// fail-safe, no masking of systemd-udevd/trigger/settle/sockets needed at
/// all. Those units stay completely untouched, so `.device` unit creation
/// (which only ever happens via real udev monitor broadcasts - masking the
/// daemon was tried and caused a hang) keeps working exactly as it does on
/// an unmodified system.
///
/// Installed with a filename that sorts before 60-persistent-storage.rules
/// (e.g. 10-fastdev-precomputed.rules) so these ENV{} assignments are in
/// place before that file's own blkid-skip check is evaluated.
fn write_fast_rules(capture: &Capture, path: &Path, subsystems: &[String]) -> Result<()> {
    let mut out = String::new();
    out.push_str("# Generated by fastdev-compile - do not edit by hand.\n");
    out.push_str("# Pre-seeds ID_FS_* properties for already-captured block devices and sets\n");
    out.push_str("# UDEV_DISABLE_PERSISTENT_STORAGE_BLKID_FLAG (the stock, documented escape\n");
    out.push_str("# hatch in 60-persistent-storage.rules) to skip the real blkid disk read for\n");
    out.push_str("# just that device. A device whose DEVPATH doesn't match any stanza here\n");
    out.push_str("# falls through to the normal stock probe, unaffected - per-device,\n");
    out.push_str("# fail-safe, no global state.\n");

    for device in &capture.devices {
        if device.subsystem != "block" {
            continue;
        }
        if !subsystems.is_empty() && !subsystems.contains(&device.subsystem) {
            continue;
        }
        let Some(devpath) = &device.devpath else {
            continue;
        };

        let mut clauses = vec![
            "SUBSYSTEM==\"block\"".to_string(),
            format!("ENV{{DEVPATH}}==\"{}\"", escape_rule_value(devpath)),
        ];
        for (key, value) in &device.properties {
            if key.starts_with("ID_FS_") {
                clauses.push(format!("ENV{{{key}}}=\"{}\"", escape_rule_value(value)));
            }
        }
        clauses.push("ENV{UDEV_DISABLE_PERSISTENT_STORAGE_BLKID_FLAG}=\"1\"".to_string());

        out.push_str(&clauses.join(", "));
        out.push('\n');
    }

    fs::write(path, out).with_context(|| format!("writing {}", path.display()))
}

fn escape_rule_value(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}
